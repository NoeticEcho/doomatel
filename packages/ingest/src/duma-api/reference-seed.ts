/**
 * Нормализует наименование фазы для сопоставления.
 * Источник отдаёт строки с двойными пробелами и завершающими точками.
 */
export function normalizePhaseName(name: string): string {
  return name.replace(/\s+/gu, ' ').replace(/\.+$/u, '').trim().toLowerCase();
}

/**
 * Ключ события хронологии.
 *
 * Именно эта функция, а не наименование фазы, определяет тождество события.
 * Отдельная функция существует ровно для того, чтобы соблазн сравнить
 * события по названию не возникал в вызывающем коде.
 */
export function eventKey(stageId: number | null | undefined, phaseId: number | null | undefined): string {
  return `${stageId ?? 'null'}.${phaseId ?? 'null'}`;
}

/** Чтение, к которому относится фаза, если это фаза рассмотрения палатой. */
export function readingNumber(stageId: number, phaseId: number): 1 | 2 | 3 | undefined {
  const key = eventKey(stageId, phaseId);
  // Все три фазы называются одинаково; различает их только стадия.
  if (key === '3.8') return 1;
  if (key === '4.11') return 2;
  if (key === '5.14') return 3;
  return undefined;
}
