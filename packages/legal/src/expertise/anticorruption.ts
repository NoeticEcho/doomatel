export const CORRUPTION_FACTOR_BY_CODE = new Map(
  CORRUPTION_FACTORS.map((factor) => [factor.code, factor]),
);

export interface MarkerHit {
  factorCode: string;
  marker: string;
  /** Позиция маркера в тексте: [start, end). */
  span: [number, number];
  /** Фрагмент текста вокруг маркера. */
  context: string;
}

/**
 * Ищет лингвистические маркеры коррупциогенных факторов.
 *
 * Это **предварительный фильтр**, а не заключение экспертизы: маркер лишь
 * указывает место, требующее оценки. Итоговый вывод делает эксперт (человек
 * или агент), опираясь на определение фактора из методики.
 */
export function findCorruptionMarkers(text: string, contextChars = 120): MarkerHit[] {
  const hits: MarkerHit[] = [];
  const normalized = text.toLowerCase().replace(/ё/gu, 'е');

  for (const factor of CORRUPTION_FACTORS) {
    for (const marker of factor.markers) {
      const needle = marker.toLowerCase().replace(/ё/gu, 'е');
      let from = 0;
      for (;;) {
        const index = normalized.indexOf(needle, from);
        if (index === -1) break;
        const start = Math.max(0, index - contextChars);
        const end = Math.min(text.length, index + needle.length + contextChars);
        hits.push({
          factorCode: factor.code,
          marker,
          span: [index, index + needle.length],
          context: text.slice(start, end).replace(/\s+/gu, ' ').trim(),
        });
        from = index + needle.length;
      }
    }
  }

  return hits.sort((a, b) => a.span[0] - b.span[0]);
}
