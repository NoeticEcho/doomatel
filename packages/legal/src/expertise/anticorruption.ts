export type CorruptionFactorGroup = 'discretion' | 'requirements';

export interface CorruptionFactor {
  /** Устойчивый код фактора: группа и буква пункта методики. */
  code: string;
  group: CorruptionFactorGroup;
  /** Пункт методики. */
  clause: string;
  /** Краткое наименование фактора по методике. */
  name: string;
  /** Определение фактора по методике. */
  definition: string;
  /**
   * Лингвистические маркеры, повышающие вероятность фактора.
   * Это не доказательство, а подсказка для агента, где смотреть внимательнее.
   */
  markers: string[];
  /** Вопрос, на который должен ответить эксперт (в том числе агент). */
  checkQuestion: string;
}

