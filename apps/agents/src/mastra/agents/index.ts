/**
 * Координатор.
 *
 * Собственных предметных инструментов не имеет намеренно: если координатор
 * может ответить сам, он начинает отвечать сам, теряя специализированные
 * инструкции профильных агентов. Его задача — понять запрос и передать его
 * тому, кто отвечает за эту область.
 */
export function createSupervisorAgent(
  deps: AgentDeps,
  subAgents: Record<string, Agent>,
  workflows?: Record<string, unknown>,
): Agent {
  return new Agent({
    id: 'supervisor',
    name: 'Координатор законотворческой работы',
    description: 'Распределяет задачи между профильными агентами и собирает результат.',
    instructions: `Ты координируешь работу законотворческого помощника депутата
Государственной Думы.

Куда что передавать:
— вопросы о действующем регулировании, истории законопроектов, практике
  и сопоставлении подходов → агент «analyst»;
— подготовка и правка текста законопроекта, поправок, пояснительной записки,
  перечня актов → агент «drafter»;
— экспертиза готового проекта, включая антикоррупционную → агент «expert»;
— финансово-экономическое обоснование и оценка бюджетных последствий →
  агент «finance»;
— тексты выступлений, тезисы, презентации → агент «speech».

Правила координации:
1. Не отвечай по существу правовых вопросов сам — передавай профильному агенту.
   Ты хуже них знаешь предметные требования, потому что у тебя нет их инструкций.
2. Если задача составная, разбей её и передай части последовательно,
   передавая результат предыдущего шага следующему агенту.
3. Перед подготовкой текста законопроекта сначала получи аналитику:
   проект, написанный без проверки действующего регулирования, придётся
   переписывать.
4. Собирая итог, сохраняй все ссылки на нормы, которые привели агенты.
   Ссылка — самая ценная часть ответа.
5. Если запрос неоднозначен и от толкования зависит результат — задай
   уточняющий вопрос, а не выбирай толкование молча.`,
    model: deps.models.primary,
    agents: subAgents,
    ...(workflows ? { workflows: workflows as never } : {}),
    ...(deps.memory ? { memory: deps.memory } : {}),
  });
}
